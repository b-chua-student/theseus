import os

from flask import Blueprint, current_app, jsonify, request
from flask.typing import ResponseReturnValue
from pydantic import BaseModel, ConfigDict, Field, ValidationError

from api.extensions import limiter

chat_bp = Blueprint("chat", __name__)


class ChatRequest(BaseModel):
    """Request payload for the chat endpoint.

    Attributes:
        manuscript_id: UUID of the manuscript being discussed.
        section_id: UUID of the currently selected section, or None.
        message: The user's message text.
        document: Plain-text content of the current section for context.
    """

    model_config = ConfigDict(extra="ignore", str_strip_whitespace=True)

    manuscript_id: str = Field(min_length=1)
    section_id: str | None = Field(default=None)
    message: str = Field(min_length=1)
    document: str = Field(default="")


def _call_gemini(message: str, document: str) -> str:
    """Call the Gemini API and return the assistant reply text.

    Args:
        message: The user's message.
        document: Plain-text content of the current section for context.

    Returns:
        The assistant's reply string.

    Raises:
        RuntimeError: If the API key is missing or the request fails.
    """
    import json as _json
    import urllib.error
    import urllib.request

    api_key = os.environ.get("GEMINI_API_KEY", "")
    if not api_key or api_key == "CHANGE_ME":
        raise RuntimeError("GEMINI_API_KEY is not configured.")

    url = (
        "https://generativelanguage.googleapis.com/v1beta/models/"
        f"gemini-2.0-flash:generateContent?key={api_key}"
    )

    system_text = "You are a helpful writing assistant. Be concise."
    if document:
        system_text += f"\n\nCurrent section content:\n{document}"

    payload = {
        "contents": [
            {"role": "user", "parts": [{"text": message}]},
        ],
        "systemInstruction": {"parts": [{"text": system_text}]},
    }

    data = _json.dumps(payload).encode()
    req = urllib.request.Request(
        url,
        data=data,
        headers={"Content-Type": "application/json"},
        method="POST",
    )

    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            body = _json.loads(resp.read())
    except urllib.error.HTTPError as exc:
        raise RuntimeError(f"Gemini API error {exc.code}: {exc.read().decode()}") from exc
    except urllib.error.URLError as exc:
        raise RuntimeError(f"Gemini request failed: {exc.reason}") from exc

    try:
        return body["candidates"][0]["content"]["parts"][0]["text"]
    except (KeyError, IndexError) as exc:
        raise RuntimeError(f"Unexpected Gemini response shape: {body}") from exc


@chat_bp.post("")
@limiter.limit("20/minute")
def chat() -> ResponseReturnValue:
    """Accept a user message and return an AI assistant reply.

    The reply is generated by the Gemini API when a valid API key is
    configured in the ``GEMINI_API_KEY`` environment variable. When no
    key is available a fallback message is returned so the frontend
    remains functional.

    Returns:
        200 with ``{"reply": "<text>"}`` on success, or 400 on invalid input.
    """
    raw_body = request.get_json(silent=True)
    if not isinstance(raw_body, dict):
        return jsonify({"error": "Request body must be a valid JSON object."}), 400

    try:
        payload = ChatRequest.model_validate(raw_body)
    except ValidationError as err:
        return jsonify({"error": err.errors()}), 400

    try:
        reply = _call_gemini(payload.message, payload.document)
    except RuntimeError as exc:
        current_app.logger.warning("Chat backend unavailable: %s", exc)
        reply = (
            "The AI assistant is not available right now "
            "(GEMINI_API_KEY is not configured). "
            "Please set it in your .env file."
        )

    return jsonify({"reply": reply}), 200
